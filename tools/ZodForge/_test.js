var r6=C.toZod('{"a":1}',{importLine:false,inferType:false});
ok('bare', r6.value.code.indexOf('import')<0&&r6.value.code.indexOf('z.infer')<0);
var r7=C.toZod('{"a":1}',{intAsInt:true});
ok('int', /z\.number\(\)\.int\(\)/.test(r7.value.code));
var r8=C.toZod('{"a-b":1}');
ok('quoted-key', /"a-b": z\.number\(\)/.test(r8.value.code));
var r9=C.toZod('{"mix":[1,"x"]}');
ok('union', /z\.union\(\[/.test(r9.value.code));
var r10=C.toZod('{"e":{}}');
ok('empty-obj', /e: z\.object\(\{\}\)/.test(r10.value.code));
var r11=C.toZod('{"arr":[]}');
ok('empty-arr', /arr: z\.array\(z\.unknown\(\)\)/.test(r11.value.code));
ok('fields', C.toZod('{"a":1,"b":{"c":2}}').value.stats.fields===3);
ok('mergeAll-null', C.mergeAll([])===null);
console.log((fail?'FAIL':'PASS')+' ZodForge '+pass+'/'+fail);process.exit(fail?1:0);
