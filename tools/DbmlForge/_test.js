
const fs=require('fs'),path=require('path');
const html=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
const m=html.match(/<script>([\s\S]*?)<\/script>/);
const mod={exports:{}};
new Function('module','exports','require',m[1])(mod,mod.exports,require);
const P=mod.exports;
let n=0; function ok(c,msg){ if(!c){ console.error('FAIL: '+msg); process.exit(1);} n++; }
const dbml='Table users {\n  id int [pk, increment]\n  email varchar(255) [not null, unique]\n}\n\nTable posts {\n  id int [pk]\n  user_id int [ref: > users.id]\n}';
ok(P.dbStripComments('a // x\nb').replace(/[ \t]+/g,'')==='a\nb','strip line comments');
ok(P.dbStripComments('a /* x */ b')==='a  b','strip block comments');
ok(P.dbParse('').error!==null,'empty error');
ok(P.dbParse('nothing here').error!==null,'no table error');
const mdl=P.dbParse(dbml);
ok(mdl.error===null && mdl.tables.length===2,'parse two tables');
ok(mdl.tables[0].name==='users','table name');
ok(mdl.tables[0].cols.length===2,'column count');
ok(mdl.tables[0].cols[0].pk===true,'pk flag');
ok(mdl.tables[0].cols[0].increment===true,'increment flag');
ok(mdl.tables[0].cols[1].notNull===true && mdl.tables[0].cols[1].unique===true,'not null unique');
ok(mdl.tables[0].cols[1].type==='varchar(255)','type with length');
ok(mdl.refs.length===1 && mdl.refs[0].to==='users','inline ref captured');
ok(mdl.refs[0].from==='posts' && mdl.refs[0].fromCol==='user_id','ref direction');
const std=P.dbParse('Table a {\n  id int [pk]\n}\n\nRef: a.id > b.aid');
ok(std.refs.length===1 && std.refs[0].to==='b','standalone Ref parsed');
const defm=P.dbParse('Table t {\n  id int [pk]\n  s timestamp [default: now()]\n}');
ok(defm.tables[0].cols[1].def==='now()','default captured');
ok(P.dbSqlType('bool','mysql')==='TINYINT(1)','mysql bool');
ok(P.dbSqlType('uuid','mysql')==='CHAR(36)','mysql uuid');
ok(P.dbSqlType('int','postgres')==='integer','pg int');
ok(P.dbSqlType('varchar(20)','postgres')==='varchar(20)','passthrough type');
const sql=P.dbToSql(mdl,'postgres');
ok(sql.indexOf('CREATE TABLE "users"')>=0,'pg create table');
ok(sql.indexOf('PRIMARY KEY ("id")')>=0,'primary key emitted');
ok(sql.indexOf('NOT NULL')>=0 && sql.indexOf('UNIQUE')>=0,'constraints emitted');
ok(sql.indexOf('GENERATED BY DEFAULT AS IDENTITY')>=0,'pg identity');
ok(sql.indexOf('FOREIGN KEY ("user_id") REFERENCES "users"')>=0,'fk emitted');
const my=P.dbToSql(mdl,'mysql');
ok(my.indexOf('`users`')>=0 && my.indexOf('AUTO_INCREMENT')>=0,'mysql quoting and increment');
ok(P.dbToSql({error:'x'},'mysql')==='','toSql guards error model');
ok(P.dbToSql(defm,'postgres').indexOf('DEFAULT now()')>=0,'default in ddl');
const st=P.dbStats(mdl);
ok(st.tables===2 && st.cols===4 && st.refs===1,'stats counts');
ok(st.pkMissing.length===0,'no missing pk');
ok(P.dbStats(P.dbParse('Table x {\n  a int\n}')).pkMissing[0]==='x','missing pk detected');
ok(P.dbStats(null).tables===0,'stats null guard');
const lint=P.dbLint(P.dbParse('Table x {\n  a int\n  a text\n}'));
ok(lint.some(s=>s.indexOf('\u5b57\u6bb5\u91cd\u590d')>=0),'lint duplicate column');
ok(lint.some(s=>s.indexOf('\u7f3a\u5c11\u4e3b\u952e')>=0),'lint missing pk');
ok(P.dbLint(P.dbParse('Table a {\n  id int [pk]\n}\n\nRef: a.id > zz.x')).some(s=>s.indexOf('\u672a\u77e5\u8868')>=0),'lint unknown ref table');
ok(P.dbLint(mdl).length===0,'clean model no lint');
const mer=P.dbMermaid(mdl);
ok(mer.indexOf('erDiagram')===0,'mermaid header');
ok(mer.indexOf('users ||--o{ posts')>=0,'mermaid relation');
ok(P.dbMermaid({error:'x'})==='','mermaid guards error');
console.log('PASS '+n+' assertions');
